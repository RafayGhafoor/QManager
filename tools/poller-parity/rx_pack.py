#!/usr/bin/env python3
"""rx_pack.py <expected.bin> <parity_dir> <out.txt> <parse_at md5> <poller md5>

Packs the device output of rx_expect.sh (NUL-separated, see that script) plus
every fixture and sidecar it names into one self-contained text file for the
Rust host tests (native/qmanager_atd/tests/parity/expected.txt).

Line format (one record per line, bytes escaped: printable ASCII except '\\'
verbatim, '\\' as '\\\\', everything else as '\\xHH'):
  F <fixture path> <content>
  E <fixture path> <sidecar .env content>
  C <case id>                (steps|rcs|fixtures)
  V <name> <value>           (globals of the preceding case that left their sentinel)
"""
import os
import sys


def esc(b: bytes) -> str:
    out = []
    for c in b:
        if c == 0x5C:
            out.append("\\\\")
        elif 0x20 <= c <= 0x7E:
            out.append(chr(c))
        else:
            out.append("\\x%02x" % c)
    return "".join(out)


def main() -> int:
    src, pdir, dst, md5_lib, md5_poller = sys.argv[1:6]
    data = open(src, "rb").read()
    cases = []
    cur = None
    for rec in data.split(b"\0"):
        if not rec:
            continue
        if rec.startswith(b"\x01"):
            cur = (rec[1:].decode(), [])
            cases.append(cur)
            continue
        name, _, val = rec.partition(b"=")
        assert cur is not None
        cur[1].append((name.decode(), val))
    fixtures = []
    for cid, _ in cases:
        for f in cid.split("|")[2].split(","):
            if f not in fixtures:
                fixtures.append(f)
    with open(dst, "w", newline="\n") as o:
        o.write("# Generated by tools/poller-parity/rx_pack.py from rx_expect.sh run on the device.\n")
        o.write("# parse_at.sh md5 %s, qmanager_poller md5 %s, %d cases.\n" % (md5_lib, md5_poller, len(cases)))
        for f in fixtures:
            p = os.path.join(pdir, f)
            o.write("F %s %s\n" % (f, esc(open(p, "rb").read())))
            if os.path.exists(p + ".env"):
                o.write("E %s %s\n" % (f, esc(open(p + ".env", "rb").read())))
        for cid, vals in cases:
            o.write("C %s\n" % cid)
            for n, v in vals:
                o.write("V %s %s\n" % (n, esc(v)))
    print("cases", len(cases), "fixtures", len(fixtures))
    return 0


if __name__ == "__main__":
    sys.exit(main())
